/** POST /tenants/{id}/{action} — single-purpose actions returning the updated tenant. */
const action = (
  path: string,
  summary: string,
  auth: EndpointDef['auth'],
  audit: EndpointDef['audit'],
  extra: Partial<EndpointDef> = {},
): EndpointDef => ({
  method: 'POST',
  path: `/tenants/{id}/${path}`,
  summary,
  auth,
  path_params: id,
  response: resource(ref('TenantDetail')),
  ...(audit ? { audit } : {}),
  example,
  ...extra,
});

